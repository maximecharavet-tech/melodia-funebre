-- ─── 2. sequences ─────────────────────────────────────────────────────
create table if not exists public.sequences (
  id          bigint generated by default as identity primary key,
  owner       text not null default '',
  nom         text not null default '',
  cible       text not null default '',
  etapes      jsonb not null default '[]'::jsonb,
  actif       boolean not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index if not exists sequences_owner_idx on public.sequences (lower(owner));

alter table public.sequences enable row level security;

drop policy if exists "chacun ses sequences" on public.sequences;
create policy "chacun ses sequences" on public.sequences
  for select to authenticated
  using (lower(owner) = lower(auth.jwt() ->> 'email') or public.est_master());

