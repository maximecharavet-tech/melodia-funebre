-- ─── 7. melodia_capacites : drapeau console_v2 ────────────────────────
-- On étend la fonction existante si elle existe, sinon on la crée.
do $$
declare
  src text;
  has_fn boolean;
begin
  select exists (
    select 1 from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.proname = 'melodia_capacites'
  ) into has_fn;
  if not has_fn then
    execute $f$
      create or replace function public.melodia_capacites()
      returns jsonb language sql stable security definer as $body$
        select jsonb_build_object('console_v2', true);
      $body$;
    $f$;
  else
    -- On remplace par une version qui expose toujours console_v2:true.
    select pg_get_functiondef(p.oid) into src
      from pg_proc p
      join pg_namespace n on n.oid = p.pronamespace
      where n.nspname = 'public' and p.proname = 'melodia_capacites' limit 1;
    execute $f$
      create or replace function public.melodia_capacites()
      returns jsonb language sql stable security definer as $body$
        select public.melodia_capacites_base() || jsonb_build_object('console_v2', true);
      $body$;
    $f$;
  end if;
end $$;

